/* Run against `python -m cpn serve --demo`. Requires npm package playwright. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.APP_URL||'http://127.0.0.1:8080');
  await page.waitForSelector('.product-card');
  assert.match(await page.locator('#notice').innerText(),/fictional/i);
  assert.equal(await page.locator('.product-card').count(),9);
  if(process.env.SCREENSHOT_DIR){fs.mkdirSync(process.env.SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:process.env.SCREENSHOT_DIR+'/desktop.png',fullPage:true});}
  await page.selectOption('#crop','Corn');
  await page.waitForFunction(()=>document.querySelectorAll('.product-card').length===3);
  await page.fill('#ingredient','thiam');
  await page.waitForFunction(()=>document.querySelectorAll('.product-card').length===1);
  await page.locator('.product-name').click();
  await page.waitForSelector('#product-dialog[open]');
  assert.equal(await page.locator('.component-table tbody tr').count(),3);
  assert.match(await page.locator('#product-detail').innerText(),/Neonicotinoid/);
  await page.keyboard.press('Escape');
  await page.click('#reset');
  await page.waitForFunction(()=>document.querySelectorAll('.product-card').length===9);
  for(let i=0;i<3;i++)await page.locator('.compare-select').nth(i).click();
  await page.locator('.compare-select').nth(3).click();
  assert.equal(await page.locator('.selected-tag').count(),3);
  assert.match(await page.locator('#toast').innerText(),/up to 3/);
  await page.click('#open-compare');
  await page.waitForSelector('#compare-dialog[open]');
  assert.equal(await page.locator('.compare-table thead th').count(),4);
  assert.match(await page.locator('#comparison').innerText(),/Target crop groups/);
  if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/comparison.png'});
  await page.keyboard.press('Escape');
  const downloadPromise=page.waitForEvent('download');await page.click('#export');const download=await downloadPromise;
  assert.equal(download.suggestedFilename(),'seed-treatment-results.csv');
  await page.reload();await page.waitForSelector('.selected-tag');assert.equal(await page.locator('.selected-tag').count(),3);
  await page.click('#clear-compare');
  await page.locator('.nav[data-tab="learn"]').click();
  await page.waitForSelector('.ingredient-card');await page.fill('#guide-search','thiamethoxam');assert.equal(await page.locator('.ingredient-card').count(),1);
  await page.locator('.nav[data-tab="data"]').click();assert.equal(await page.locator('#sites-list li').count(),14);
  await page.locator('.nav[data-tab="explore"]').click();
  await page.route('**/api/products?**',route=>route.fulfill({status:503,body:'Unavailable'}));
  await page.fill('#search','test');await page.waitForSelector('#retry-results');
  await page.unroute('**/api/products?**');await page.fill('#search','');await page.click('#retry-results');await page.waitForSelector('.product-card');
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed: crop/ingredient filters, details, 3-product limit, matrix, export, persistence, guide, errors, and mobile layout.');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
